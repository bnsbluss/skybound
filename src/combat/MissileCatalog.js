export function defaultUnlockedMissileIds() {
  return MISSILES.filter((m) => !m.cost).map((m) => m.id);
}

export function getMissile(id) {
  return MISSILES.find((m) => m.id === id) ?? MISSILES[0];
}

export function isMissileUnlocked(id, unlocked = []) {
  const spec = getMissile(id);
  if (!spec.cost) return true;
  return Array.isArray(unlocked) && unlocked.includes(spec.id);
}
